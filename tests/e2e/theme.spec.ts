import { expect, test } from '@playwright/test'

test('cycles scenes, follows hash changes, and stops after manual selection', async ({ page }) => {
  await page.clock.install()
  await page.goto('./theme.html')
  const strip = page.getByRole('button', { name: 'Strip board' })
  const rail = page.getByRole('button', { name: 'Policy time rail' })
  const form = page.getByRole('button', { name: 'Claim form' })
  await expect(strip).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.strip-layer').first()).toContainText('98')
  expect(await page.locator('.belt').first().innerHTML()).toEqual(await page.locator('.belt').last().innerHTML())
  await page.clock.fastForward(14_000)
  await expect(rail).toHaveAttribute('aria-pressed', 'true')
  await form.click()
  await expect(page).toHaveURL(/#form$/)
  await page.clock.fastForward(30_000)
  await expect(form).toHaveAttribute('aria-pressed', 'true')
  await page.evaluate(() => { location.hash = 'rail' })
  await expect(rail).toHaveAttribute('aria-pressed', 'true')
})

test('shows the static final scene for reduced motion and adapts the form grid', async ({ page, isMobile }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('./theme.html#form')
  const form = page.getByRole('button', { name: 'Claim form' })
  await expect(form).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.field')).toHaveCount(12)
  await expect(page.locator('.stamp')).toHaveCSS('animation-name', 'none')
  await expect(page.locator('.stamp')).toBeVisible()
  const columns = await page.locator('.fields').evaluate(element => getComputedStyle(element).gridTemplateColumns)
  expect(columns.split(' ')).toHaveLength(isMobile ? 2 : 6)
  await page.getByRole('button', { name: 'Policy time rail' }).click()
  await expect(page.getByText('the service date picks the policy version')).toHaveCSS('opacity', '1')
  const markers = await page.locator('#pins circle').evaluateAll(elements => elements.map(element => Number(element.getAttribute('cx'))))
  expect(markers).toEqual([8, 88, 91, 102].map(day => 24 + 612 * day / 181))
})
